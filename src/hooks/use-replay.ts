"use client";

/**
 * TanStack Query hook for regulatory replay — §3.4.4 + §4.4.
 *
 *   useReplayInstruction()
 *
 * The hook wraps a useMutation that POSTs an instructionId to
 * /api/v1/replay. The server reconstructs the policy decision tree
 * using the policyVersion that was active at decision time.
 *
 * Truth state: WIRED. Endpoint returns synthetic replay output for
 * INS-003 (the canonical pilot demo) when DB is not provisioned.
 */

import { type UseMutationResult, useMutation, useQueryClient } from "@tanstack/react-query";

import { type ApiClientError, apiClient } from "@/lib/api-client";

export interface ReplayResult {
  instructionId: string;
  policyVersion: string;
  decision: string;
  reason: string;
  finality: string;
  reproducible: boolean;
  replayedAt: string;
}

export type ReplayInput = string | { instructionId: string };

/**
 * Mutation hook. The caller passes either a raw string (the instructionId)
 * or an object `{ instructionId }`. Both shapes are normalised inside
 * the mutationFn before POSTing.
 */
export function useReplayInstruction(
  initialInstructionId?: string,
): UseMutationResult<ReplayResult, ApiClientError, ReplayInput> {
  const qc = useQueryClient();
  return useMutation<ReplayResult, ApiClientError, ReplayInput>({
    mutationFn: (input) => {
      const instructionId = typeof input === "string" ? input : input.instructionId;
      const idempotencyKey = initialInstructionId
        ? `replay-${instructionId}-${initialInstructionId}`
        : `replay-${instructionId}`;
      return apiClient.post<ReplayResult>("/replay", { instructionId }, { idempotencyKey });
    },
    onSuccess: async () => {
      // Invalidate the instruction detail so the timeline page reflects
      // any fresh evidence generated by the replay (Phase 3 wiring).
      await qc.invalidateQueries({ queryKey: ["instructions"] });
    },
  });
}
