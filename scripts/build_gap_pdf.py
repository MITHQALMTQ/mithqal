# ━━ Helpers ━━
def P(text, style=st_body):
    return Paragraph(text, style)

def cell(text, bold=False, muted=False):
    """Wrap a literal text cell. Auto-escapes < and > unless they form a known ReportLab inline tag."""
    if bold:
        return Paragraph(esc(text), st_cell_bold)
    if muted:
        return Paragraph(esc(text), st_cell_muted)
    return Paragraph(esc(text), st_cell)

def esc(text):
    """Escape literal < and > that aren't part of ReportLab inline tags.
    Only restores <b>/<i> (never <a>, <font>, <super>, <sub> — those would be ambiguous in literal cell text)."""
    import html as _html
    t = _html.escape(text, quote=False)
    for tag in ('b', 'i'):
        t = t.replace(f'&lt;{tag}&gt;', f'<{tag}>').replace(f'&lt;/{tag}&gt;', f'</{tag}>')
    return t

# (cell_safe removed — cell() now auto-escapes via esc())

def gap_status_badge(status_str):
    """Return a small Table cell containing a colored status pill."""
    if status_str == 'IMPLEMENTED':
        bg, fg, glyph = SEM_SUCCESS, colors.white, 'IMPLEMENTED'
    elif status_str == 'GAP':
        bg, fg, glyph = SEM_ERROR, colors.white, 'GAP'
    else:  # PARTIAL
        bg, fg, glyph = SEM_WARNING, colors.white, 'PARTIAL'
    t = Table([[glyph]], colWidths=[22*mm], rowHeights=[6.5*mm])
    t.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,-1), bg),
        ('TEXTCOLOR',  (0,0), (-1,-1), fg),
        ('FONTSIZE',   (0,0), (-1,-1), 7.5),
        ('FONTNAME',   (0,0), (-1,-1), 'DejaVuSans-Bold'),
        ('ALIGN',      (0,0), (-1,-1), 'CENTER'),
        ('VALIGN',     (0,0), (-1,-1), 'MIDDLE'),
    ]))
    return t

def make_table(headers, rows, col_widths, header_text_color=colors.white):
    data = [headers] + rows
    tbl = Table(data, colWidths=col_widths, repeatRows=1)
    style_cmds = [
        ('BACKGROUND', (0,0), (-1,0), TABLE_HEADER_COLOR),
        ('TEXTCOLOR',  (0,0), (-1,0), header_text_color),
        ('FONTNAME',   (0,0), (-1,0), 'DejaVuSans-Bold'),
        ('FONTSIZE',   (0,0), (-1,0), 8),
        ('ALIGN',      (0,0), (-1,0), 'LEFT'),
        ('VALIGN',     (0,0), (-1,-1), 'TOP'),
        ('LEFTPADDING',(0,0), (-1,-1), 4),
        ('RIGHTPADDING',(0,0),(-1,-1), 4),
        ('TOPPADDING', (0,0), (-1,-1), 4),
        ('BOTTOMPADDING',(0,0),(-1,-1), 4),
        ('GRID',       (0,0), (-1,-1), 0.25, BORDER),
        ('FONTNAME',   (0,1), (-1,-1), 'FreeSerif'),
        ('FONTSIZE',   (0,1), (-1,-1), 8.5),
    ]
    for i in range(1, len(data)):
        if i % 2 == 0:
            style_cmds.append(('BACKGROUND', (0,i), (-1,i), TABLE_ROW_ODD))
        else:
            style_cmds.append(('BACKGROUND', (0,i), (-1,i), TABLE_ROW_EVEN))
    tbl.setStyle(TableStyle(style_cmds))
    return tbl

